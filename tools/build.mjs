import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist');
const PLUGIN = path.join(ROOT, 'dsh-gbc-theme');
fs.mkdirSync(DIST, { recursive: true });
fs.mkdirSync(path.join(PLUGIN, 'lib'), { recursive: true });

function read(name) {
  return fs.readFileSync(path.join(SRC, name), 'utf8');
}

const fonts = read('fonts.css');
const css = read('wallpaper.css');
const dshCss = read('dsh-theme.css');
const markup = read('markup.html');
const js = read('wallpaper.js');
const template = read('index.template.html');

// ---------------------------------------------------------------------------
// 1. standalone, single-file wallpaper
// ---------------------------------------------------------------------------
let html = template;
html = html.split('/*__FONTS__*/').join(fonts);
html = html.split('/*__CSS__*/').join(css);
html = html.split('<!--__MARKUP__-->').join(markup);
html = html.split('/*__JS__*/').join(js);
const out = path.join(DIST, 'index.html');
fs.writeFileSync(out, html);
console.log(`built ${out} (${(fs.statSync(out).size / 1024).toFixed(1)} KiB)`);

// ---------------------------------------------------------------------------
// 2. DSH client bundle
// ---------------------------------------------------------------------------
const bundleCss = `${fonts}\n\n${css}\n\n${dshCss}`;
const client = `/* Generated by tools/build.mjs — do not edit by hand.
   GBC / 空の箱 dynamic wallpaper for the DeepSeek Harness web shell. */
(function () {
  var CSS = ${JSON.stringify(bundleCss)};
  var MARKUP = ${JSON.stringify(markup)};

  ${js}

  if (!window.__ModuleLoader__) {
    console.warn('[dsh-gbc-theme] __ModuleLoader__ not found');
    return;
  }

  window.__ModuleLoader__.load({
    id: 'dsh-gbc-theme',
    factory: function (require) {
      var module = { exports: {} };
      var state = null;

      function apply(ctx) {
        if (state || window.__gbcDshMounted) return;
        state = { style: null, host: null, wall: null, chip: null, disposed: false, shellObserver: null, modeObserver: null };

        // A wallpaper preset is also an appearance preset: LIVE needs the dark
        // shell, SKY/NOISE need the light shell. Without this the chat keeps
        // light-theme black text over a suddenly dark LIVE background.
        function syncShellTheme(mode, retry) {
          if (!state || state.disposed) return;
          var api = null;
          try {
            api = ctx && typeof ctx.get === 'function' ? ctx.get('theme') : null;
          } catch (error) {
            api = null;
          }
          if (!api || typeof api.setTheme !== 'function') {
            if (retry !== false) {
              setTimeout(function () { syncShellTheme(mode, false); }, 300);
            } else {
              applyDomTheme(mode);
            }
            return;
          }
          var want = mode === 'live' ? 'dark' : 'light';
          try {
            var current = typeof api.getTheme === 'function' ? api.getTheme() : null;
            if (!current || current.preference !== want) api.setTheme(want);
            // The host write is async. Verify the resolved DOM palette and
            // fall back to the CSS attribute if the theme service is a no-op.
            setTimeout(function () {
              if (!state || state.disposed || !document.body) return;
              var isDark = document.body.hasAttribute('data-ds-dark-theme');
              if ((want === 'dark') !== isDark) applyDomTheme(mode);
            }, 450);
          } catch (error) {
            console.warn('[dsh-gbc-theme] could not sync DSH appearance', error);
            applyDomTheme(mode);
          }
        }

        // Last-resort sync when the theme service is unavailable or the host
        // write is rejected: body[data-ds-dark-theme] is the CSS source of
        // truth for both DSH tokens and our scrim.
        function applyDomTheme(mode) {
          if (!state || state.disposed || !document.body) return;
          var dark = mode === 'live';
          if (dark) document.body.setAttribute('data-ds-dark-theme', '');
          else document.body.removeAttribute('data-ds-dark-theme');
          setShellFlag();
        }

        // The top strip needs a readable ground for the project name even if a
        // theme write is still in flight. Track the resolved shell palette too.
        function setShellFlag() {
          if (!state || !state.wall || state.disposed) return;
          var shell = document.body && document.body.hasAttribute('data-ds-dark-theme') ? 'dark' : 'light';
          state.wall.root.setAttribute('data-shell', shell);
          document.documentElement.setAttribute('data-gbc-shell', shell);
        }

        var style = document.createElement('style');
        style.setAttribute('data-gbc-theme', '');
        style.textContent = CSS;
        document.head.appendChild(style);
        state.style = style;

        var host = document.createElement('div');
        host.id = 'gbc-dsh-mount';
        host.innerHTML = MARKUP;
        document.body.appendChild(host);
        state.host = host;
        document.documentElement.classList.add('gbc-theme-on');
        document.documentElement.setAttribute('data-gbc-theme', 'on');

        var onReady = function () {
          if (!state || state.disposed) return;
          var wall = window.GBCWallpaper.mount(host, {
            dsh: true,
            standalone: false,
            hud: false
          });
          if (!wall) return;
          state.wall = wall;
          window.__gbcWallpaper = wall;

          var chip = document.createElement('button');
          chip.type = 'button';
          chip.className = 'gbc-dsh-chip';
          chip.title = 'GBC theme — click to cycle LIVE / SKY / NOISE';
          chip.innerHTML = '<i></i><span>GBC</span><b>' + String(wall.mode).toUpperCase() + '</b>';
          chip.addEventListener('click', function () {
            wall.cycleMode();
          });
          document.body.appendChild(chip);
          state.chip = chip;
          wall.root.addEventListener('gbc-mode', function (e) {
            var label = chip.querySelector('b');
            if (label) label.textContent = String(e.detail).toUpperCase();
            syncShellTheme(e.detail);
          });
          syncShellTheme(wall.mode);
          setShellFlag();

          // Fallbacks: some HMR paths update the root attribute without
          // dispatching a CustomEvent; the body palette can also lag behind
          // the theme write. Observe both instead of relying on one signal.
          state.shellObserver = new MutationObserver(setShellFlag);
          state.shellObserver.observe(document.body, {
            attributes: true,
            attributeFilter: ['data-ds-dark-theme']
          });
          state.modeObserver = new MutationObserver(function () {
            syncShellTheme(wall.mode, false);
          });
          state.modeObserver.observe(wall.root, {
            attributes: true,
            attributeFilter: ['data-mode']
          });
        };

        if (document.readyState === 'loading') {
          document.addEventListener('DOMContentLoaded', onReady, { once: true });
        } else {
          onReady();
        }

        var dispose = function () {
          if (!state || state.disposed) return;
          state.disposed = true;
          document.removeEventListener('DOMContentLoaded', onReady);
          if (state.shellObserver) state.shellObserver.disconnect();
          if (state.modeObserver) state.modeObserver.disconnect();
          if (state.wall) state.wall.destroy();
          if (state.chip && state.chip.parentNode) state.chip.parentNode.removeChild(state.chip);
          if (state.host && state.host.parentNode) state.host.parentNode.removeChild(state.host);
          if (state.style && state.style.parentNode) state.style.parentNode.removeChild(state.style);
          document.documentElement.classList.remove('gbc-theme-on');
          document.documentElement.removeAttribute('data-gbc-theme');
          state = null;
          window.__gbcDshMounted = false;
        };

        if (ctx && typeof ctx.effect === 'function') {
          ctx.effect(function () { return dispose; }, 'dsh-gbc-theme: wallpaper');
        } else {
          window.addEventListener('beforeunload', dispose, { once: true });
        }
        window.__gbcDshMounted = true;
      }

      module.exports = { name: 'dsh-gbc-theme', inject: [], apply: apply };
      return module.exports;
    }
  });
})();
`;
const clientOut = path.join(PLUGIN, 'lib', 'client.js');
fs.writeFileSync(clientOut, client);
console.log(`built ${clientOut} (${(fs.statSync(clientOut).size / 1024).toFixed(1)} KiB)`);
